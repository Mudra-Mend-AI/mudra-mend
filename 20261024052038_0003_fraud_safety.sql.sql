/*
# Fraud & safety: scam reports, alerts, cases, case timeline

Tables that capture user-submitted scam reports, system-generated safety alerts,
investigation cases, and a per-case timeline of actions.

## New Tables
1. scam_reports — reports submitted by users about suspected scams
2. alerts — safety notifications for users (generated by payment engine or manually)
3. cases — investigation cases managed by fraud analysts / investigators
4. case_timeline — append-only log of actions on a case

## Security
- RLS on all tables.
- scam_reports: owner-scoped SELECT (user sees their reports). INSERT owner-scoped.
- alerts: owner-scoped CRUD (user reads/marks-read their alerts).
- cases: authenticated SELECT (dashboards list cases across the org).
- case_timeline: authenticated SELECT; INSERT authenticated (app controls who writes).
*/

-- Scam reports (created before alerts/cases that reference it)
CREATE TABLE IF NOT EXISTS scam_reports (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES profiles(id) ON DELETE CASCADE,
  category text NOT NULL,
  description text NOT NULL DEFAULT '',
  transaction_id uuid REFERENCES transactions(id) ON DELETE SET NULL,
  suspect_contact text,
  evidence_url text,
  status text NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted','under_review','verified','rejected','escalated')),
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE scam_reports ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON scam_reports TO authenticated;
DROP POLICY IF EXISTS "scam_select_own" ON scam_reports;
CREATE POLICY "scam_select_own" ON scam_reports FOR SELECT TO authenticated
  USING (auth.uid() = user_id);
DROP POLICY IF EXISTS "scam_insert_own" ON scam_reports;
CREATE POLICY "scam_insert_own" ON scam_reports FOR INSERT TO authenticated
  WITH CHECK (auth.uid() = user_id);
DROP POLICY IF EXISTS "scam_update_own" ON scam_reports;
CREATE POLICY "scam_update_own" ON scam_reports FOR UPDATE TO authenticated
  USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
DROP POLICY IF EXISTS "scam_delete_own" ON scam_reports;
CREATE POLICY "scam_delete_own" ON scam_reports FOR DELETE TO authenticated
  USING (auth.uid() = user_id);
CREATE INDEX IF NOT EXISTS idx_scam_reports_user_id ON scam_reports(user_id);
CREATE INDEX IF NOT EXISTS idx_scam_reports_suspect_contact ON scam_reports(suspect_contact);

-- Alerts (created before cases because cases.related_alert_id references alerts)
CREATE TABLE IF NOT EXISTS alerts (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES profiles(id) ON DELETE CASCADE,
  category text NOT NULL DEFAULT 'payment_safety',
  priority text NOT NULL DEFAULT 'medium' CHECK (priority IN ('low','medium','high','critical')),
  title text NOT NULL,
  body text NOT NULL DEFAULT '',
  related_transaction_id uuid REFERENCES transactions(id) ON DELETE SET NULL,
  related_case_id uuid,
  is_read boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE alerts ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON alerts TO authenticated;
DROP POLICY IF EXISTS "alerts_select_own" ON alerts;
CREATE POLICY "alerts_select_own" ON alerts FOR SELECT TO authenticated
  USING (auth.uid() = user_id);
DROP POLICY IF EXISTS "alerts_insert_own" ON alerts;
CREATE POLICY "alerts_insert_own" ON alerts FOR INSERT TO authenticated
  WITH CHECK (auth.uid() = user_id);
DROP POLICY IF EXISTS "alerts_update_own" ON alerts;
CREATE POLICY "alerts_update_own" ON alerts FOR UPDATE TO authenticated
  USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
DROP POLICY IF EXISTS "alerts_delete_own" ON alerts;
CREATE POLICY "alerts_delete_own" ON alerts FOR DELETE TO authenticated
  USING (auth.uid() = user_id);
CREATE INDEX IF NOT EXISTS idx_alerts_user_id ON alerts(user_id);
CREATE INDEX IF NOT EXISTS idx_alerts_is_read ON alerts(is_read);

-- Cases
CREATE TABLE IF NOT EXISTS cases (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','under_investigation','pending_review','closed','escalated')),
  priority text NOT NULL DEFAULT 'medium' CHECK (priority IN ('low','medium','high','critical')),
  assigned_to uuid REFERENCES profiles(id) ON DELETE SET NULL,
  organization_id uuid REFERENCES organizations(id) ON DELETE SET NULL,
  related_alert_id uuid REFERENCES alerts(id) ON DELETE SET NULL,
  related_scam_report_id uuid REFERENCES scam_reports(id) ON DELETE SET NULL,
  notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE cases ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT, UPDATE, DELETE ON cases TO authenticated;
DROP POLICY IF EXISTS "cases_select_authenticated" ON cases;
CREATE POLICY "cases_select_authenticated" ON cases FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "cases_insert_authenticated" ON cases;
CREATE POLICY "cases_insert_authenticated" ON cases FOR INSERT TO authenticated WITH CHECK (true);
DROP POLICY IF EXISTS "cases_update_authenticated" ON cases;
CREATE POLICY "cases_update_authenticated" ON cases FOR UPDATE TO authenticated USING (true) WITH CHECK (true);
CREATE INDEX IF NOT EXISTS idx_cases_status ON cases(status);
CREATE INDEX IF NOT EXISTS idx_cases_assigned_to ON cases(assigned_to);

-- Link alerts.related_case_id now that cases exists
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.table_constraints WHERE constraint_name = 'alerts_related_case_id_fkey') THEN
    ALTER TABLE alerts ADD CONSTRAINT alerts_related_case_id_fkey
      FOREIGN KEY (related_case_id) REFERENCES cases(id) ON DELETE SET NULL;
  END IF;
END $$;

-- Case timeline
CREATE TABLE IF NOT EXISTS case_timeline (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  case_id uuid NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
  action text NOT NULL,
  note text,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE case_timeline ENABLE ROW LEVEL SECURITY;
GRANT SELECT, INSERT ON case_timeline TO authenticated;
DROP POLICY IF EXISTS "timeline_select_authenticated" ON case_timeline;
CREATE POLICY "timeline_select_authenticated" ON case_timeline FOR SELECT TO authenticated USING (true);
DROP POLICY IF EXISTS "timeline_insert_authenticated" ON case_timeline;
CREATE POLICY "timeline_insert_authenticated" ON case_timeline FOR INSERT TO authenticated WITH CHECK (true);
CREATE INDEX IF NOT EXISTS idx_case_timeline_case_id ON case_timeline(case_id);

-- updated_at trigger for cases
DROP TRIGGER IF EXISTS cases_set_updated_at ON cases;
CREATE TRIGGER cases_set_updated_at BEFORE UPDATE ON cases
  FOR EACH ROW EXECUTE FUNCTION set_updated_at();
